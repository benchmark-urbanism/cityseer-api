#!/usr/bin/env python
"""
05_figures_validation.py - Generate the reach-comparison figure (ablation rung 1).

Reads the ground-truth caches and produces:
  - fig6_reach_comparison.pdf:     Canonical grid reach vs actual network reach

The former fig2/fig4/fig5 generators (canonical-schedule error, accuracy, and speedup
figures) were removed: those figures have no home in the paper scaffold, and the
per-node method's equivalents are generated by 09_figure_adaptive_comparison.py.

Usage:
    python 05_figures_validation.py
"""

import pickle
import sys
from pathlib import Path

import matplotlib
import matplotlib.ticker

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from cityseer.sampling import GRID_SPACING
from matplotlib import patheffects

sys.path.insert(0, str(Path(__file__).parent))
import figstyle
from utilities import CACHE_DIR, FIGURES_DIR

# =============================================================================
# CONFIGURATION
# =============================================================================

DISTANCES_KM = [1, 2, 5, 10, 20]

figstyle.apply()


# =============================================================================
# FIG 6: CANONICAL REACH VS ACTUAL REACH
# =============================================================================


def load_reach_data() -> list[dict]:
    """Load mean reach per network and distance from ground truth caches."""
    rows = []

    # GLA
    for dist in [1000, 2000, 5000, 10000, 20000]:
        p = CACHE_DIR / f"gla_ground_truth_{dist}m.pkl"
        if p.exists():
            with open(p, "rb") as f:
                d = pickle.load(f)
            rows.append({"network": "Greater London (metro)", "distance": dist, "mean_reach": d["mean_reach"]})

    # Madrid
    for dist in [1000, 2000, 5000, 10000, 20000]:
        p = CACHE_DIR / f"madrid_ground_truth_{dist}m.pkl"
        if p.exists():
            with open(p, "rb") as f:
                d = pickle.load(f)
            rows.append({"network": "Madrid (metro)", "distance": dist, "mean_reach": d["mean_reach"]})

    # Cary (suburban)
    for dist in [1000, 2000, 5000, 10000, 20000]:
        p = CACHE_DIR / f"cary_ground_truth_{dist}m.pkl"
        if p.exists():
            with open(p, "rb") as f:
                d = pickle.load(f)
            rows.append({"network": "Cary (suburban)", "distance": dist, "mean_reach": d["mean_reach"]})

    # The Woodlands (held-out suburban)
    for dist in [1000, 2000, 5000, 10000, 20000]:
        p = CACHE_DIR / f"woodlands_ground_truth_{dist}m.pkl"
        if p.exists():
            with open(p, "rb") as f:
                d = pickle.load(f)
            rows.append(
                {"network": "The Woodlands (suburban, held-out)", "distance": dist, "mean_reach": d["mean_reach"]}
            )

    return rows


def generate_fig6_reach_comparison():
    """Figure 6: Canonical grid reach vs actual network reach.

    The canonical model r = π*d²/s² underpins the distance-based p schedule.
    Networks above the canonical curve are denser than assumed — the schedule
    is conservative (over-samples) for them. Networks below are sparser, so
    the deterministic schedule under-samples relative to reach-based Hoeffding.
    """
    print("\nGenerating Figure 6: canonical vs actual reach...")

    reach_rows = load_reach_data()
    if not reach_rows:
        print("  No reach data found — skipping.")
        return

    df = pd.DataFrame(reach_rows)

    # Authored at 5.5x3.5in and included at 0.75\textwidth (4.72in) so the render
    # scale is ~0.86: SIZE_ANNOT prints above the 7pt floor and the tick/legend type
    # matches the width=\textwidth siblings (fig12/fig13) rather than shrinking below them.
    fig, ax = plt.subplots(figsize=(5.5, 3.5))

    # Canonical curve. Grey is the dedicated canonical colour across the figure set
    # (fig12/fig13); kept the heaviest line (lw=2.0) so it still reads as the baseline
    # and separates in greyscale despite the lighter hue. Drawn past the axis right
    # edge so the curve and the half-plane tints reach the plot boundary.
    d_fine = np.geomspace(850, 35000, 300)
    r_canonical = np.pi * d_fine**2 / GRID_SPACING**2
    ax.plot(
        d_fine / 1000,
        r_canonical,
        "-",
        color=figstyle.COLOR_CANONICAL,
        linewidth=2.0,
        label=f"Canonical grid model ($s$={GRID_SPACING:.0f}m)",
        zorder=5,
    )

    # Real networks (dense metros above the canonical curve, sparse suburbs below).
    # Colour and marker come from the shared per-network scale; the linestyle is a
    # third channel so the four series separate in greyscale as well.
    network_styles = {
        "Greater London (metro)": ("gla", "-"),
        "Madrid (metro)": ("madrid", "--"),
        "Cary (suburban)": ("cary", ":"),
        "The Woodlands (suburban, held-out)": ("woodlands", "-."),
    }

    for network, (key, ls) in network_styles.items():
        subset = df[df["network"] == network].sort_values("distance")
        if subset.empty:
            continue
        ax.plot(
            subset["distance"] / 1000,
            subset["mean_reach"],
            marker=figstyle.NETWORK_MARKERS[key],
            linestyle=ls,
            color=figstyle.NETWORK_COLORS[key],
            markersize=7,
            linewidth=1.4,
            label=network,
            alpha=0.9,
        )

    # annotate the assumed-vs-measured gap on the held-out network at 20 km, in its series colour
    wood = df[df["network"] == "The Woodlands (suburban, held-out)"]
    w20 = wood[wood["distance"] == 20000]
    if not w20.empty:
        measured = float(w20.iloc[0]["mean_reach"])
        assumed = float(np.pi * 20000**2 / GRID_SPACING**2)
        wood_colour = figstyle.NETWORK_COLORS["woodlands"]
        # Draw the double-headed span just clear of the 20 km marker column, so both
        # arrowheads show and neither the shaft nor the heads collide with the Cary
        # triangle or the Woodlands diamond. The endpoints stay at the true 20 km
        # measured and assumed reach, so the 2.6x ratio is honest; at x=20.4 the
        # canonical line (42,691) sits ~4% above the assumed head, so the top reads
        # as meeting the line while the shaft clears the 20 km markers.
        arrow_x = 20.4
        ax.annotate(
            "",
            xy=(arrow_x, measured),
            xytext=(arrow_x, assumed),
            arrowprops={"arrowstyle": "<->", "color": wood_colour, "lw": 1.4},
        )
        # Label the gap to the right of the arrow, level with its midpoint (the
        # geometric mean of the endpoints on the log axis), so it clears the canonical
        # line and every series and reads without a tangle.
        ax.text(
            21.3,
            np.sqrt(measured * assumed),
            f"assumed reach\n{assumed / measured:.1f}× measured",
            fontsize=figstyle.SIZE_ANNOT,
            color=wood_colour,
            ha="left",
            va="center",
            path_effects=[patheffects.withStroke(linewidth=3.0, foreground="white")],
        )

    Y_MIN, Y_MAX = 30, 2e5
    ax.set_xscale("log")
    ax.set_yscale("log")
    ax.set_xlabel("Distance (km)")
    ax.set_ylabel("Mean measured reach (nodes)")
    ax.set_xticks([1, 2, 5, 10, 20])
    ax.xaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(lambda x, _: f"{x:g}"))
    ax.xaxis.set_minor_formatter(matplotlib.ticker.NullFormatter())
    ax.set_xlim(0.85, 28)
    ax.legend(loc="upper left", fontsize=figstyle.SIZE_LEGEND)
    ax.grid(True, which="major")
    ax.yaxis.set_major_formatter(matplotlib.ticker.FuncFormatter(lambda x, _: f"{x:,.0f}"))

    # Tint the half-planes either side of the canonical curve, out to the axis limits.
    # Cool neutral grey above, warm semantic-free tan below: the split reads without
    # borrowing the betweenness red for a decorative "bad region" wash.
    ax.fill_between(d_fine / 1000, r_canonical, Y_MAX, color=figstyle.COLOR_MUTED, alpha=0.11, label="_nolegend_")
    ax.fill_between(d_fine / 1000, Y_MIN, r_canonical, color=figstyle.COLOR_WARN, alpha=0.11, label="_nolegend_")
    # Region labels one step larger and darker than SIZE_ANNOT/COLOR_CANONICAL, so
    # they survive the 0.75-textwidth placement in single-column print. Single lines:
    # the caption carries the oversamples/under-samples reading, and one line keeps
    # the denser label clear of both the legend text and the London line's 20 km end
    # in the top-right pocket.
    ax.text(
        27,
        1.7e5,
        "Denser than canonical",
        fontsize=figstyle.SIZE_LEGEND,
        color="#4A4A4A",
        ha="right",
        va="center",
        style="italic",
    )
    ax.text(
        12,
        42,
        "Sparser than canonical",
        fontsize=figstyle.SIZE_LEGEND,
        color="#4A4A4A",
        ha="center",
        va="bottom",
        style="italic",
    )
    ax.set_ylim(Y_MIN, Y_MAX)

    plt.tight_layout()
    out = FIGURES_DIR / "fig6_reach_comparison.pdf"
    fig.savefig(out, dpi=300, bbox_inches="tight")
    plt.close()
    print(f"  Saved: {out}")


# =============================================================================
# MAIN
# =============================================================================


def main():
    print("=" * 70)
    print("05_figures_validation.py - Validation Figures")
    print("=" * 70)

    generate_fig6_reach_comparison()

    print("\nDone. Figures saved to:", FIGURES_DIR)
    return 0


if __name__ == "__main__":
    exit(main())
