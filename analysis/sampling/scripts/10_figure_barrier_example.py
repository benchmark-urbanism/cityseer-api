#!/usr/bin/env python
"""
10_figure_barrier_example.py - Ablation rung 2 illustration: Euclidean disc vs network reach.

Selects the live Cary node with the largest ratio of Euclidean neighbour count to network
reach at 10 km, then draws the nodes inside the Euclidean disc against the set actually
reached by a bounded network traversal from that node, with the boundary of the reached
set drawn as a contour. A map count includes nodes the network traversal cannot reach
within the distance limit; the pilot poll does not.

Diagnostics on the exemplar (network-distance field from a 30 km traversal) show no
discrete barrier: the distance field is smooth, and the excluded nodes' path circuity
(median 1.62) matches the reached nodes' (1.70). The mechanism is ordinary circuity
acting on a disc population concentrated at 7-10 km straight-line distance east of the
node, so the figure labels the reachable/unreachable boundary rather than a named barrier.

Outputs:
    - paper/figures/fig14_disc_vs_reach.pdf
    - paper/tables/barrier_macros.tex (\\barrierDiscCount, \\barrierReach, \\barrierRatio),
      so the caption and prose numbers cannot desync from a regenerated figure
"""

import importlib.util
import pickle
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import figstyle
import matplotlib.pyplot as plt
import numpy as np
from matplotlib import patheffects
from matplotlib.lines import Line2D
from matplotlib.patches import Circle
from scipy.ndimage import gaussian_filter
from scipy.spatial import KDTree
from utilities import CACHE_DIR, FIGURES_DIR, TABLES_DIR

DIST = 10000
MIN_REACH = 50  # ignore tiny-reach nodes when selecting the exemplar

figstyle.apply()


def main() -> int:
    spec = importlib.util.spec_from_file_location("cary_val", Path(__file__).parent / "03_validate_cary.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    net, nodes_gdf, live_mask, _ = mod.load_cary_network()

    with open(CACHE_DIR / f"cary_ground_truth_{DIST}m.pkl", "rb") as f:
        gt = pickle.load(f)
    reach = np.asarray(gt["node_reach"], dtype=float)  # live nodes only

    xs = nodes_gdf["x"].to_numpy(float)
    ys = nodes_gdf["y"].to_numpy(float)
    pts = np.column_stack([xs, ys])
    tree = KDTree(pts)
    live_pts = pts[np.asarray(live_mask, dtype=bool)]
    disc_counts = tree.query_ball_point(live_pts, r=float(DIST), return_length=True, workers=-1)
    disc_counts = np.asarray(disc_counts, dtype=float)

    valid = reach >= MIN_REACH
    ratios = np.where(valid, disc_counts / np.maximum(reach, 1.0), 0.0)
    sel_live = int(np.argmax(ratios))
    print(f"Exemplar live node {sel_live}: disc count {disc_counts[sel_live]:.0f}, "
          f"network reach {reach[sel_live]:.0f}, ratio {ratios[sel_live]:.1f}")

    def _tex_int(n: float) -> str:
        return f"{int(n):,}".replace(",", "{,}")

    macros_path = TABLES_DIR / "barrier_macros.tex"
    with open(macros_path, "w") as f:
        f.write("% AUTO-GENERATED by 10_figure_barrier_example.py - do not edit manually\n")
        f.write("% Exemplar-node numbers for fig14; regenerated together with the figure.\n")
        f.write(f"\\newcommand{{\\barrierDiscCount}}{{{_tex_int(disc_counts[sel_live])}}}\n")
        f.write(f"\\newcommand{{\\barrierReach}}{{{_tex_int(reach[sel_live])}}}\n")
        f.write(f"\\newcommand{{\\barrierRatio}}{{{ratios[sel_live]:.1f}}}\n")
    print(f"  Saved: {macros_path}")

    node_idxs = np.asarray(net.node_indices(), dtype=np.int64)
    live_idxs = node_idxs[np.asarray(live_mask, dtype=bool)]
    src_raw = int(live_idxs[sel_live])
    sx, sy = live_pts[sel_live]

    reachable, visits = net.dijkstra_tree_shortest(src_raw, DIST, 1.0)
    r_idx = np.fromiter(reachable, dtype=np.int64)
    r_dist = np.fromiter((visits[j].short_dist for j in reachable), dtype=np.float64, count=len(r_idx))
    reached_raw = set(r_idx[r_dist <= DIST].tolist())

    compact = np.full(int(node_idxs.max()) + 1, -1, dtype=np.int64)
    compact[node_idxs] = np.arange(len(node_idxs), dtype=np.int64)
    reached_mask = np.zeros(len(node_idxs), dtype=bool)
    reached_mask[[compact[j] for j in reached_raw]] = True

    in_disc = np.hypot(xs - sx, ys - sy) <= DIST
    disc_only = in_disc & ~reached_mask

    margin = 0.08 * DIST
    window = (
        (xs >= sx - DIST - margin)
        & (xs <= sx + DIST + margin)
        & (ys >= sy - DIST - margin)
        & (ys <= sy + DIST + margin)
    )

    # Reachable/unreachable boundary: classify a grid by the mean reached state of the
    # k nearest network nodes, smooth, clip to the disc, and contour the 0.5 level.
    grid_step = 150.0
    knn = 8
    gx = np.arange(sx - DIST - margin, sx + DIST + margin, grid_step)
    gy = np.arange(sy - DIST - margin, sy + DIST + margin, grid_step)
    grid_x, grid_y = np.meshgrid(gx, gy)
    grid_pts = np.column_stack([grid_x.ravel(), grid_y.ravel()])
    nn_dist, nn_idx = tree.query(grid_pts, k=knn, workers=-1)
    grid_val = reached_mask[nn_idx].mean(axis=1).reshape(grid_x.shape)
    # Smooth firmly (sigma 2.2) so the sparse western pockets and the small
    # inlets/peninsulas along the eastern edge stop spawning tiny closed
    # 0.5-crossings, leaving one coherent eastern frontier.
    grid_val = gaussian_filter(grid_val, sigma=2.2)
    # Mask grid cells with no nearby network node so the contour hugs the point
    # cloud instead of bridging empty ground.
    empty = nn_dist[:, 0].reshape(grid_x.shape) > 1000.0
    grid_val[gaussian_filter(empty.astype(float), sigma=1.0) > 0.5] = np.nan
    grid_val[np.hypot(grid_x - sx, grid_y - sy) > DIST] = np.nan

    fig, ax = plt.subplots(figsize=(7.2, 7.2))
    # Colour semantics (figstyle): the per-node method's reachable set is the accent
    # (orange), the Euclidean disc-only excess is the canonical distance-only count
    # (grey), and context nodes outside the disc are faint. The disc-only grey is a
    # darkened step of COLOR_CANONICAL: the orange dots print near 60% grey (alpha
    # over white), so the standard #737373 would converge with them in greyscale.
    colour_disc_only = "#5A5A5A"
    ax.scatter(xs[window & ~in_disc], ys[window & ~in_disc], s=0.6,
               color=figstyle.COLOR_FAINT, rasterized=True)
    ax.scatter(xs[disc_only], ys[disc_only], s=0.9,
               color=colour_disc_only, rasterized=True)
    # Slightly smaller and semi-transparent so a dense cul-de-sac cluster of
    # near-duplicate nodes reads as a smear rather than parallel tally strokes.
    ax.scatter(xs[reached_mask], ys[reached_mask], s=0.7, alpha=0.85,
               color=figstyle.COLOR_METHOD, rasterized=True)
    # Contour the 0.5 level, then keep only substantial arcs: the empty-cell masking
    # still spawns a few short strays in the sparse western half that bound nothing
    # the eye can parse. Dropping arcs below a fraction of the longest one leaves the
    # coherent eastern frontier that separates the reached set from the disc-only mass.
    cs = ax.contour(grid_x, grid_y, np.ma.masked_invalid(grid_val), levels=[0.5])
    segs = list(cs.allsegs[0])
    cs.remove()
    seg_lens = [
        float(np.hypot(np.diff(s[:, 0]), np.diff(s[:, 1])).sum()) if len(s) > 1 else 0.0
        for s in segs
    ]
    if seg_lens:
        keep_len = max(0.20 * max(seg_lens), 6 * grid_step)
        for s, seg_len in zip(segs, seg_lens, strict=True):
            if seg_len >= keep_len:
                ax.plot(s[:, 0], s[:, 1], color=figstyle.COLOR_INK, linewidth=1.0, zorder=4)
    ax.add_patch(Circle((sx, sy), DIST, fill=False, linestyle="--",
                        edgecolor=figstyle.COLOR_INK, linewidth=1.2))
    ax.plot(sx, sy, "*", color=figstyle.COLOR_INK, markersize=14, zorder=5)
    ax.set_aspect("equal")
    ax.set_xlim(sx - DIST - margin, sx + DIST + margin)
    ax.set_ylim(sy - DIST - margin, sy + DIST + margin)
    ax.set_xticks([])
    ax.set_yticks([])
    for side in ("top", "right", "bottom", "left"):
        ax.spines[side].set_visible(False)
    # North arrow in the sparse upper-left corner, so the caption's "eastern block"
    # rests on an explicit orientation rather than the east=right convention alone.
    halo = [patheffects.withStroke(linewidth=3.0, foreground="white")]
    ax.annotate(
        "", xy=(0.055, 0.955), xytext=(0.055, 0.875), xycoords="axes fraction",
        arrowprops=dict(arrowstyle="-|>", color=figstyle.COLOR_INK, lw=1.2,
                        path_effects=halo),
    )
    ax.text(0.055, 0.965, "N", transform=ax.transAxes, ha="center", va="bottom",
            fontsize=figstyle.SIZE_ANNOT, fontweight="bold", color=figstyle.COLOR_INK,
            path_effects=halo)
    # Headline numbers on the map itself (the same computed values the macros carry),
    # in the sparse lower-left corner, so the disc-vs-reach gap reads at first glance.
    ax.text(
        0.02, 0.02,
        (f"disc: {int(disc_counts[sel_live]):,} / reached: {int(reach[sel_live]):,} "
         f"({ratios[sel_live]:.1f}×)"),
        transform=ax.transAxes, ha="left", va="bottom", fontsize=figstyle.SIZE_LEGEND,
        color=figstyle.COLOR_INK,
        bbox=dict(facecolor="white", alpha=0.85, edgecolor="none", pad=2.5),
    )
    handles = [
        Line2D([0], [0], marker="*", color=figstyle.COLOR_INK, linestyle="none",
               markersize=12, label="Exemplar node"),
        Line2D([0], [0], marker="o", color=figstyle.COLOR_METHOD, linestyle="none", markersize=6,
               label=f"Reached on the network ({int(reach[sel_live]):,} nodes)"),
        Line2D([0], [0], marker="o", color=colour_disc_only, linestyle="none", markersize=6,
               label=(f"In the Euclidean disc only ({int(disc_counts[sel_live] - reach[sel_live]):,} "
                      f"of {int(disc_counts[sel_live]):,} nodes)")),
        Line2D([0], [0], marker="o", color=figstyle.COLOR_FAINT, linestyle="none", markersize=7,
               label="Network nodes outside the disc"),
        Line2D([0], [0], color=figstyle.COLOR_INK, linestyle="-", linewidth=1.0,
               label="Boundary of the reached set (smoothed contour)"),
        Line2D([0], [0], color=figstyle.COLOR_INK, linestyle="--",
               label=f"{DIST // 1000} km Euclidean disc"),
    ]
    # Place the legend below the map so it never overlaps the reached-set contour
    # (its top-left arc entered the old upper-left legend box). Two columns keep the
    # six entries compact under the square panel; no frame, per the figstyle convention.
    ax.legend(handles=handles, loc="upper center", bbox_to_anchor=(0.5, -0.01),
              ncol=2, frameon=False)
    figstyle.scale_bar(ax, 2000, loc="lower right")
    plt.tight_layout()
    out = FIGURES_DIR / "fig14_disc_vs_reach.pdf"
    fig.savefig(out, bbox_inches="tight")
    print(f"  Saved: {out}")
    plt.close()
    return 0


if __name__ == "__main__":
    exit(main())
