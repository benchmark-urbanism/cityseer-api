#!/usr/bin/env python
"""
forced_closeness_check.py - Sampled closeness on the suburbs with the work test bypassed.

On the suburban networks the work test routes closeness-only calls to exact
computation at every distance, so the validation contains no sampled suburban
closeness cell. A joint centrality call can nevertheless sample suburban
closeness (with-betweenness work pricing). This script supplies the missing
evidence: it forces the per-node sampled closeness path at 20 km on Cary and
The Woodlands, using the same pilot poll and per-node probabilities as the
runtime, and scores it against the cached exact ground truth.

Requires the cached networks and ground truths (run 03/04 first).

Usage:
    python forced_closeness_check.py

Outputs:
    output/forced_closeness.csv
    paper/tables/forced_macros.tex
"""

import importlib.util
import pickle
from pathlib import Path

import numpy as np
import pandas as pd
from cityseer.sampling import compute_node_p, estimate_polled_reach
from utilities import CACHE_DIR, OUTPUT_DIR, TABLES_DIR, compute_accuracy_metrics

DISTANCE = 20000
N_RUNS = 3

NETWORKS = {
    "cary": ("03_validate_cary.py", "load_cary_network"),
    "woodlands": ("04_validate_woodlands.py", "load_woodlands_network"),
}

MACRO_NAMES = {"cary": "caryForcedClosenessRho", "woodlands": "woodlandsForcedClosenessRho"}


def _load_network(network: str):
    script, loader_name = NETWORKS[network]
    spec = importlib.util.spec_from_file_location(f"{network}_val", Path(__file__).parent / script)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return getattr(mod, loader_name)()


def main() -> int:
    rows = []
    macro_lines = [
        "% AUTO-GENERATED by forced_closeness_check.py - do not edit manually",
        f"% Sampled closeness forced past the work test on the suburbs at {DISTANCE // 1000}km,",
        "% scored against the exact ground truth (mean over three seeds; per-seed pilot).",
    ]
    for network in sorted(NETWORKS):
        net, _nodes_gdf, live_mask, _ = _load_network(network)
        with open(CACHE_DIR / f"{network}_ground_truth_{DISTANCE}m.pkl", "rb") as f:
            gt = pickle.load(f)
        true_h = np.asarray(gt["harmonic"], dtype=float)
        rhos = []
        for seed in range(N_RUNS):
            # Mirror the runtime: the pilot poll and the source draw share the call's seed.
            reach_lcb, _, _ = estimate_polled_reach(net, [DISTANCE], random_seed=42 + seed)
            q = compute_node_p(reach_lcb[DISTANCE])
            res = net.centrality_shortest(
                distances=[DISTANCE],
                closeness_exprs=[("harmonic", "1/c")],
                betweenness_exprs=[],
                compute_cycles=False,
                sample_probability=1.0,
                sampling_weights=[float(v) for v in q],
                random_seed=42 + seed,
                pbar_disabled=True,
            )
            est_h = np.array(res.metrics["harmonic"][DISTANCE])[live_mask]
            sp, _, _, _, _ = compute_accuracy_metrics(true_h, est_h)
            rhos.append(float(sp))
            print(f"  {network} seed {seed}: rho={sp:.4f} (mean q={float(np.mean(q)):.2f})")
        rows.append(
            {
                "network": network,
                "distance": DISTANCE,
                "rho_closeness": float(np.mean(rhos)),
                "rho_closeness_std": float(np.std(rhos)),
                "rho_closeness_min": float(np.min(rhos)),
                "n_seeds": len(rhos),
            }
        )
        macro_lines.append(f"\\newcommand{{\\{MACRO_NAMES[network]}}}{{{np.mean(rhos):.4f}}}")
        print(f"{network}: rho_c={np.mean(rhos):.4f} (min {np.min(rhos):.4f}, std {np.std(rhos):.4f})")
    df = pd.DataFrame(rows)
    out = OUTPUT_DIR / "forced_closeness.csv"
    df.to_csv(out, index=False)
    print(f"Saved {out}")
    macros_out = TABLES_DIR / "forced_macros.tex"
    with open(macros_out, "w") as f:
        f.write("\n".join(macro_lines) + "\n")
    print(f"Saved {macros_out}")
    return 0


if __name__ == "__main__":
    exit(main())
